#!/usr/bin/env python3
"""Generate docs/ASSIGNMENTS.md (tracked) from metrics/splits/split100.json and the image files' assigned_to.

    metrics/run.sh tools/assignments.py

Per annotator tag (current name from annotators.json): the assigned images in annotation order (val, then test,
then train; then by stem), with the data split and reflective_advisory. Also copies the draw54 contact sheet
(metrics/runs/splits/draw54.png, git-ignored) to docs/img/draw54_contact_sheet.jpg when it exists.
"""

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from core import annotators as AN  # noqa: E402
from core import config as K  # noqa: E402


def main():
    cfg = K.load_config()
    ann = K.repo_path(cfg["paths"]["annotations"])
    names = AN.names(ann / "annotators.json")
    order = cfg["annotate"]["image_order"]
    rows = []
    for x in json.loads(K.repo_path(cfg["paths"]["split_assignment"]).read_text())["images"]:
        f = json.loads((ann / f"{x['stem']}.json").read_text())
        rows.append(dict(stem=x["stem"], split=f["split"], assigned_to=f["assigned_to"], set=f["set"],
                         reflective=bool(f.get("reflective_advisory"))))
    L = ["# Image assignments", "",
         "Generated by `metrics/run.sh tools/assignments.py` from `metrics/splits/split100.json` and each image file's",
         "`assigned_to`. Do not edit by hand. Annotate in this order: **val, then test, then train**.", "",
         "*reflective (advisory)*: the image looked glossy or reflective on the contact sheet. Annotate it as usual; avoid",
         "patches on shiny spots.", ""]
    ids = sorted({r["assigned_to"] for r in rows}, key=lambda i: (i == "yueren", names.get(i, i)))
    for i in ids:
        mine = sorted((r for r in rows if r["assigned_to"] == i), key=lambda r: (order.index(r["split"]), r["stem"]))
        cnt = {s: sum(r["split"] == s for r in mine) for s in order}
        L += [f"## {names.get(i, i)} (tag id `{i}`): {len(mine)} images (" + ", ".join(f"{s} {cnt[s]}" for s in order) + ")", "",
              "| # | image | split | reflective (advisory) |", "|---|---|---|---|"]
        L += [f"| {k} | `{r['stem']}` | {r['split']} | {'yes' if r['reflective'] else ''} |" for k, r in enumerate(mine, 1)]
        L.append("")
    sheet = K.METRICS / "runs" / "splits" / "draw54.png"
    if sheet.exists():
        import cv2
        im = cv2.imread(str(sheet))
        cv2.imwrite(str(K.METRICS / "docs" / "img" / "draw54_contact_sheet.jpg"), im, [cv2.IMWRITE_JPEG_QUALITY, 82])
    if (K.METRICS / "docs" / "img" / "draw54_contact_sheet.jpg").exists():
        L += ["## Contact sheet of the 54 drawn images", "", "Numbers are the draw ranks (`metrics/splits/draw54.json`).", "",
              "![draw54 contact sheet](img/draw54_contact_sheet.jpg)", ""]
    (K.METRICS / "docs" / "ASSIGNMENTS.md").write_text("\n".join(L) + "\n")
    print(K.METRICS / "docs" / "ASSIGNMENTS.md")


if __name__ == "__main__":
    main()
